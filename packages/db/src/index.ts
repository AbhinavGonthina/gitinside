/**
 * `@gitinside/db`: the Postgres schema, client, and migrations shared by
 * `apps/web` and `apps/worker` (ADR-0057).
 */
import { fileURLToPath } from "node:url";
import { drizzle, type PostgresJsDatabase } from "drizzle-orm/postgres-js";
import { migrate } from "drizzle-orm/postgres-js/migrator";
import postgres from "postgres";
import * as schema from "./schema.js";

export * from "./schema.js";
export { schema };

/** A Drizzle database bound to GitInside's schema. */
export type Database = PostgresJsDatabase<typeof schema>;

/** A database plus the function that closes its connections. */
export interface DbHandle {
  db: Database;
  close: () => Promise<void>;
}

/** Options for {@link createDb}. */
export interface CreateDbOptions {
  /** Maximum connections in the pool (default 5; serverless callers use 1). */
  max?: number;
}

/** The folder of SQL migrations generated by drizzle-kit, shipped with the package. */
export const migrationsFolder = fileURLToPath(new URL("../drizzle", import.meta.url));

/**
 * Opens a connection pool to `url`. Prepared statements are off so the same
 * client works through Neon's pooled (PgBouncer transaction-mode) endpoint.
 */
export function createDb(url: string, options: CreateDbOptions = {}): DbHandle {
  const client = postgres(url, { max: options.max ?? 5, prepare: false, onnotice: () => {} });
  return {
    db: drizzle(client, { schema }),
    close: () => client.end({ timeout: 5 }),
  };
}

/**
 * Applies every pending migration to the database at `url`, in order, inside
 * Drizzle's migration table. Use a direct (unpooled) connection: migrations
 * take locks and need a session the pooler won't hand to someone else.
 */
export async function runMigrations(url: string): Promise<void> {
  const { db, close } = createDb(url, { max: 1 });
  try {
    await migrate(db, { migrationsFolder });
  } finally {
    await close();
  }
}
