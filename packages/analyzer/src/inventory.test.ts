import { mkdir, mkdtemp, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { AnalysisError, buildInventory, formatCount, isGeneratedHeader } from "./inventory.js";

let dir: string;
beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "gitinside-inv-"));
});
afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

async function put(path: string, content = "export {};\n"): Promise<void> {
  const full = join(dir, path);
  await mkdir(dirname(full), { recursive: true });
  await writeFile(full, content);
}

describe("buildInventory", () => {
  it("lists files sorted by full path with forward slashes", async () => {
    await put("b.ts");
    await put("a/c.ts");
    await put("a-b.ts");
    await put("README.md", "# hi\n");
    const inv = await buildInventory(dir);
    // "a-b.ts" sorts before "a/c.ts" because '-' < '/'; a depth-first walk alone would get this wrong.
    expect(inv.files).toEqual(["README.md", "a-b.ts", "a/c.ts", "b.ts"]);
    expect(inv.sourceFiles).toEqual(["a-b.ts", "a/c.ts", "b.ts"]);
    expect(inv.warnings).toEqual([]);
  });

  it("counts every source extension and nothing else", async () => {
    for (const ext of ["ts", "tsx", "mts", "cts", "js", "jsx", "mjs", "cjs", "prisma"]) {
      await put(`src/f.${ext}`);
    }
    await put("src/data.json", "{}");
    await put("docker-compose.yml", "services: {}\n");
    const inv = await buildInventory(dir);
    expect(inv.sourceFiles).toHaveLength(9);
    expect(inv.files).toContain("src/data.json");
    expect(inv.files).toContain("docker-compose.yml");
  });

  it("skips ignored directories at any depth without warnings", async () => {
    const dirs = ["node_modules", ".git", "dist", "build", ".next", "coverage", "vendor"];
    for (const d of [...dirs, "storybook-static"]) {
      await put(`${d}/x.js`);
      await put(`packages/app/${d}/y.js`);
    }
    await put("packages/app/src/index.ts");
    const inv = await buildInventory(dir);
    expect(inv.files).toEqual(["packages/app/src/index.ts"]);
    expect(inv.warnings).toEqual([]);
  });

  it("skips generated files by name and by header marker, with warnings", async () => {
    await put("public/lib.min.js", "!function(){}();");
    await put("src/gen.ts", "/* @generated by codegen */\nexport const a = 1;\n");
    await put("src/proto.ts", "// Code generated by protoc. DO NOT EDIT.\nexport {};\n");
    await put(
      "src/real.ts",
      `export const x = 1;\n${"//\n".repeat(400)}// mentions @generated below the header\n`,
    );
    const inv = await buildInventory(dir);
    expect(inv.sourceFiles).toEqual(["src/real.ts"]);
    expect(inv.warnings).toEqual([
      {
        code: "SKIPPED_GENERATED",
        file: "public/lib.min.js",
        message: "generated file skipped (minified)",
      },
      {
        code: "SKIPPED_GENERATED",
        file: "src/gen.ts",
        message: "generated file skipped (header marker)",
      },
      {
        code: "SKIPPED_GENERATED",
        file: "src/proto.ts",
        message: "generated file skipped (header marker)",
      },
    ]);
  });

  it("only treats markers near the top of the file as headers", () => {
    expect(isGeneratedHeader("// @generated\n")).toBe(true);
    expect(isGeneratedHeader("/* Auto-generated file. Do not edit. */")).toBe(true);
    expect(isGeneratedHeader(`${"x".repeat(2000)}\n// @generated`)).toBe(false);
    expect(isGeneratedHeader("const generated = true;")).toBe(false);
    expect(isGeneratedHeader("// DO NOT EDIT: generated from schema.json")).toBe(true);
    expect(isGeneratedHeader("// Do not edit without updating the docs.")).toBe(false);
    expect(isGeneratedHeader("// do not edit\n// the generated client lives elsewhere")).toBe(
      false,
    );
  });

  it("skips files over the size limit with a warning", async () => {
    await put("src/big.ts", "x".repeat(101));
    await put("src/ok.ts", "x".repeat(100));
    const inv = await buildInventory(dir, { maxFileBytes: 100 });
    expect(inv.files).toEqual(["src/ok.ts"]);
    expect(inv.warnings).toEqual([
      {
        code: "SKIPPED_LARGE",
        file: "src/big.ts",
        message: "file is 101 bytes, over the 100 byte limit; skipped",
      },
    ]);
  });

  it("defaults the size limit to 2 MB", async () => {
    await put("src/big.ts", "x".repeat(2 * 1024 * 1024 + 1));
    const inv = await buildInventory(dir);
    expect(inv.files).toEqual([]);
    expect(inv.warnings.map((w) => w.code)).toEqual(["SKIPPED_LARGE"]);
  });

  it("never follows symlinks", async () => {
    const outside = await mkdtemp(join(tmpdir(), "gitinside-outside-"));
    try {
      await writeFile(join(outside, "secret.ts"), "export {};\n");
      await put("src/index.ts");
      // A junction needs no admin rights on Windows; the type is ignored elsewhere.
      await symlink(outside, join(dir, "src", "escape"), "junction");
      const inv = await buildInventory(dir);
      expect(inv.files).toEqual(["src/index.ts"]);
      expect(inv.warnings).toEqual([
        { code: "SKIPPED_SYMLINK", file: "src/escape", message: "symbolic link not followed" },
      ]);
    } finally {
      await rm(outside, { recursive: true, force: true });
    }
  });

  it("stops descending past the depth limit with a warning", async () => {
    await put("a/b/c/deep.ts");
    await put("a/b/ok.ts");
    const inv = await buildInventory(dir, { maxDepth: 2 });
    expect(inv.files).toEqual(["a/b/ok.ts"]);
    expect(inv.warnings).toEqual([
      {
        code: "SKIPPED_DEPTH",
        file: "a/b/c",
        message: "directory nested deeper than 2 levels; skipped",
      },
    ]);
  });

  it("fails with LIMIT_FILES when over the source-file limit", async () => {
    await put("a.ts");
    await put("b.ts");
    await put("c.ts");
    await put("notes.md", "not source\n");
    const error = await buildInventory(dir, { maxSourceFiles: 2 }).catch((e: unknown) => e);
    expect(error).toBeInstanceOf(AnalysisError);
    expect((error as AnalysisError).code).toBe("LIMIT_FILES");
    expect((error as AnalysisError).message).toBe(
      "LIMIT_FILES: this repo has 3 source files, over the 2 limit. Try analyzing a subfolder.",
    );
  });

  it("allows exactly the limit and excludes generated files from the count", async () => {
    await put("a.ts");
    await put("b.ts");
    await put("c.min.js");
    const inv = await buildInventory(dir, { maxSourceFiles: 2 });
    expect(inv.sourceFiles).toEqual(["a.ts", "b.ts"]);
  });

  it("is deterministic across runs", async () => {
    await put("z/y.ts");
    await put("A.ts");
    await put("a.ts");
    await put("big.ts", "x".repeat(50));
    const a = await buildInventory(dir, { maxFileBytes: 10 });
    const b = await buildInventory(dir, { maxFileBytes: 10 });
    expect(a).toEqual(b);
  });
});

describe("formatCount", () => {
  it("groups thousands without depending on the machine locale", () => {
    expect(formatCount(7)).toBe("7");
    expect(formatCount(20000)).toBe("20,000");
    expect(formatCount(1234567)).toBe("1,234,567");
  });
});
